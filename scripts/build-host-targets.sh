  }
} else if (transaction?.version === 2) {
  if (!objectMap(transaction.binding)
      || transaction.binding.registryPath !== registryPath
      || transaction.binding.registryDirectoryIdentity !== registryDirectoryIdentity
      || transaction.binding.ownershipPath !== ownershipPath
      || transaction.binding.ownershipDirectoryIdentity !== ownershipDirectoryIdentity) {
    throw new Error("MCP transaction binding does not match the active publication namespace");
  }
} else {
  throw new Error("unsupported MCP transaction version");
}

function decode(label, state, output) {
  if (!objectMap(state) || typeof state.present !== "boolean") {
    throw new Error(`invalid ${label} transaction state`);
  }
  if (!state.present) {
    if (state.bytes !== null || state.sha256 !== null) {
      throw new Error(`invalid absent ${label} transaction state`);
    }
    return false;
  }
  if (typeof state.bytes !== "string" || typeof state.sha256 !== "string") {
    throw new Error(`invalid present ${label} transaction state`);
  }
  const bytes = Buffer.from(state.bytes, "base64");
  if (bytes.toString("base64") !== state.bytes) {
    throw new Error(`non-canonical ${label} transaction bytes`);
  }
  if (createHash("sha256").update(bytes).digest("hex") !== state.sha256) {
    throw new Error(`${label} transaction checksum mismatch`);
  }
  const value = JSON.parse(bytes.toString("utf8"));
  if (label === "registry") {
    if (!objectMap(value?.mcpServers)) {
      throw new Error("transaction registry must contain an mcpServers object");
    }
  } else {
    const targets = value?.targets;
    const valuesValid = objectMap(targets) && Object.values(targets).every(
      (name) => typeof name === "string" && name.length > 0,
    ) && new Set(Object.values(targets)).size === Object.values(targets).length;
    const keysValid = value?.version === 1
      ? Object.keys(targets ?? {}).every(
        (target) => /^[a-z0-9][a-z0-9-]*$/.test(target),
      )
      : value?.version === 2
        && Object.keys(targets ?? {}).every(
          (target) => /^[0-9a-f]{64}:[a-z0-9][a-z0-9-]*$/.test(target),
        );
    if (!valuesValid || !keysValid) {
      throw new Error("transaction ownership must contain a supported versioned targets object");
    }
  }
  writeFileSync(output, bytes, {mode: 0o600});
  return true;
}

